# -- Tipe Data Python - Part 1 --
print(int(5.3)) # Output: 5
print(int("6")) # Output: 6

# float()
print(float(3)) # Output: 3.0
print(float("9.23")) # Output: 9.23

# Boolean --> bool()
print(bool(1)) # Output: True
print(bool(0)) # Output: False

# -- Tipe Data Python - Part 2 --
# str()
print(str(5.3)) # Output: "5.3"
print(str([1, 'buku'])) # Output: "[1, 'buku']"

# list()
print(list("buku")) # Output: ['b', 'u', 'k', 'u']
print(list((1,2,3))) # Output: [1, 2, 3]
print(list({1,3,6,3})) # Output: [1, 3, 6]

# tuple()
print(tuple("buku")) # Output: ('b', 'u', 'k', 'u')
print(tuple((1, 2, 3))) # Output: (1, 2, 3)
print(tuple({1,3,6,3})) # Output: (1, 3, 6)

# set()
print(set("buku")) # Output: {'k', 'b', 'u'}
print(set((1,2,3))) # Output: {1, 2, 3}
print(set([1,3,6,3])) # Output: {1, 3, 6}

